// 학생 연구 동의서 양식 (로드맵 3단계, 사용자 결정 2026-11-27: IRB 받음/안 받음에 따라 양식이 달라진다)
// 관리자의 연구 윤리 설정(state/accountStore.js ethics)으로 빈칸을 채운다. "# "로 시작하는 줄은 소제목으로 보인다.
// 넣은 뒤 교사가 설문과 연구 동의 화면에서 고칠 수 있다. 실제 IRB 제출용은 기관 양식에 맞추어야 한다.

const or = (v, fallback) => (String(v ?? '').trim() || fallback);

/** e: ethics → { title, body } */
export function consentTemplate(e) {
  const title = or(e.studyTitle, '(연구 제목)');
  const pi = or(e.piName, '(연구책임자 이름, 소속)');
  const piContact = or(e.piContact, '(연락처)');
  if (e.irb) {
    return {
      title: '연구 참여 설명문 및 동의서',
      body: [
        `# 연구 제목: ${title}`,
        `연구책임자: ${pi}, 연락처: ${piContact}`,
        `IRB 승인번호: ${or(e.approvalNo, '(승인번호)')}`,
        '# 1. 연구의 목적',
        '이 연구는 증명 수업에서 AI가 학생의 생각을 어떻게 도울 수 있는지, AI를 활용한 수업이 증명 능력과 AI 리터러시에 어떤 영향을 주는지 알아보기 위한 것입니다.',
        '# 2. 참여 방법과 기간',
        '수업 시간에 이 앱으로 증명을 쓰고, AI와 대화하고, 두 증명을 비교해 최종 증명을 씁니다. 활동 전후에 설문에 답합니다. 일부 학생은 수업 뒤 면담을 요청받을 수 있으며, 면담과 녹음은 따로 동의를 받습니다.',
        '# 3. 수집하는 자료',
        '쓴 증명(글과 필기), AI와 나눈 대화, 설문 응답, 활동 시간과 작성 과정, 선생님의 채점 결과를 수집합니다. 이름 대신 연구 번호로 저장하며, 이름과 연구 번호를 잇는 표는 연구책임자만 볼 수 있습니다.',
        '# 4. 위험과 이익',
        '활동은 평소 수업과 같아 예상되는 위험은 거의 없습니다. 참여하면 증명과 AI 활용 능력을 기를 수 있고, 연구 결과는 더 나은 수업을 만드는 데 쓰입니다.',
        '# 5. 자발적 참여와 철회',
        '참여는 자유이며, 참여하지 않아도 수업 활동은 똑같이 하고 성적이나 평가에 불이익이 없습니다. 언제든 이 화면에서 참여를 그만둘 수 있습니다. 그만두면 그 뒤의 자료는 수집하지 않고, 그전에 모은 자료는 연구에 사용합니다.',
        '# 6. 개인정보 보호와 자료 보관',
        `연구 자료는 연구가 끝난 뒤 ${Number(e.retentionYears || 3)}년 동안 보관한 뒤 파기합니다. 연구 결과는 학생을 알아볼 수 없는 형태로만 발표합니다.`,
        '# 7. 문의',
        `연구에 대해 궁금한 점은 연구책임자(${piContact})에게, 참여자의 권리에 대해서는 기관생명윤리위원회(${or(e.irbContact, '(IRB 연락처)')})에 문의할 수 있습니다.`,
        '# 동의',
        '위 내용을 읽고 이해했으며, 스스로 연구 참여 여부를 정합니다. 보호자 동의서는 종이로 따로 받습니다.',
      ].join('\n'),
    };
  }
  return {
    title: '연구 참여 동의',
    body: [
      `# ${title}`,
      `이 활동은 우리 학교 수업 개선 연구의 일부입니다(연구 담당: ${pi}, 연락처: ${piContact}). 학교의 승인을 받아 진행합니다.`,
      '활동에서 쓴 증명, AI와 나눈 대화, 설문 응답, 활동 시간 같은 기록을 연구에 사용합니다.',
      '연구 자료는 이름 대신 연구 번호로 다루고, 정해진 날짜가 지나면 지웁니다.',
      '참여하지 않아도 수업 활동은 똑같이 할 수 있고, 성적이나 평가에 불이익이 없습니다.',
      '동의한 뒤에도 언제든지 이 화면에서 참여를 그만둘 수 있습니다. 그만두면 그 뒤의 기록은 연구에 쓰지 않고, 그전에 모은 자료는 연구에 사용합니다.',
      '보호자께는 안내문과 동의서를 따로 보내 드립니다.',
    ].join('\n'),
  };
}
