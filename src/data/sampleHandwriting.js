const place = (strokes, [x0, y0, x1, y1]) => strokes.map((s) => s.map(([x, y]) => [x0 + x * (x1 - x0), y0 + y * (y1 - y0)]));

function hangulStrokes(ch) {
  const code = ch.charCodeAt(0) - 0xac00;
  const l = L_LIST[Math.floor(code / 588)];
  const v = V_LIST[Math.floor((code % 588) / 28)];
  const t = T_LIST[code % 28];
  const out = [];
  if (V_VOWEL[v]) {
    out.push(...place(CONSONANT[l], t ? [0.02, 0.02, 0.56, 0.5] : [0.02, 0.12, 0.58, 0.88]));
    out.push(...place(V_VOWEL[v], t ? [0.5, 0.0, 0.98, 0.6] : [0.52, 0.0, 1.0, 1.0]));
    if (t) out.push(...place(CONSONANT[t], [0.15, 0.64, 0.85, 1.0]));
  } else if (H_VOWEL[v]) {
    out.push(...place(CONSONANT[l], t ? [0.2, 0.0, 0.8, 0.34] : [0.18, 0.0, 0.82, 0.5]));
    out.push(...place(H_VOWEL[v], t ? [0.0, 0.3, 1.0, 0.62] : [0.0, 0.42, 1.0, 0.92]));
    if (t) out.push(...place(CONSONANT[t], [0.18, 0.68, 0.82, 1.0]));
  } else {
    const [h, vv] = COMPOUND[v];
    out.push(...place(CONSONANT[l], t ? [0.05, 0.0, 0.55, 0.32] : [0.05, 0.0, 0.58, 0.45]));
    out.push(...place(H_VOWEL[h], t ? [0.0, 0.26, 0.66, 0.58] : [0.0, 0.4, 0.66, 0.85]));
    out.push(...place(V_VOWEL[vv], t ? [0.58, 0.0, 1.0, 0.62] : [0.6, 0.0, 1.0, 1.0]));
    if (t) out.push(...place(CONSONANT[t], [0.18, 0.68, 0.82, 1.0]));
  }
  return out;
}

