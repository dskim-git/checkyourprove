// ── 배치와 시간 ─────────────────

function rng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s ^ (s >>> 15), 2246822507) + 0x9e3779b9) >>> 0;
    s ^= s >>> 13;
    return (s >>> 0) / 4294967296;
  };
}

const CELL = 46; // 한글 한 글자 칸(논리 단위)
const LINE = 80;
const LEFT = 28;
const TOP = 34;
const RIGHT = INK_WIDTH - 28;

function glyphOf(ch) {
  const code = ch.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) return { w: 1, s: hangulStrokes(ch) };
  return GLYPHS[ch] ?? GLYPHS[ch.toLowerCase()] ?? { w: 0.5, s: [[[0.3, 0.6], [0.7, 0.6]]] };
}

/** 선분을 촘촘한 점으로 나눈다 */
function densify(points, step = 5) {
  const out = [points[0]];
  for (let i = 1; i < points.length; i += 1) {
    const [ax, ay] = points[i - 1];
    const [bx, by] = points[i];
    const n = Math.max(1, Math.ceil(Math.hypot(bx - ax, by - ay) / step));
    for (let k = 1; k <= n; k += 1) out.push([ax + ((bx - ax) * k) / n, ay + ((by - ay) * k) / n]);
  }
  return out;
}

/**
 * 글(text)을 손글씨 필기 기록으로 만든다.
 * @param {string} text 여러 줄 가능
 * @param {{ seed?: number, startedAt?: string }} options
 */
export function handwritingInk(text, { seed = 1, startedAt = '2026-11-18T09:05:00+09:00' } = {}) {
  const rand = rng(seed);
  const jitter = (amount) => (rand() - 0.5) * 2 * amount;
  const ink = { v: 1, w: INK_WIDTH, h: INK_START_HEIGHT, startedAt, strokes: [], ops: [], sample: true };
  const size = CELL * (0.95 + rand() * 0.12);
  const slant = 0.05 + rand() * 0.08;
  let clock = 1500;
  let y = TOP;
  String(text).split('\n').forEach((line, lineIndex) => {
    if (lineIndex > 0) {
      y += LINE;
      clock += 900 + rand() * 2500; // 다음 줄로 넘어가며 생각하는 시간
    }
    let x = LEFT + jitter(4);
    let drift = 0;
    [...line].forEach((ch) => {
      if (ch === ' ') {
        x += size * SPACE;
        clock += 120;
        return;
      }
      const glyph = glyphOf(ch);
      const w = size * glyph.w;
      if (x + w > RIGHT) {
        x = LEFT + jitter(4);
        y += LINE;
        clock += 700;
      }
      drift += jitter(0.8);
      const scale = 0.92 + rand() * 0.14;
      const ox = x + jitter(1.5);
      const oy = y + drift + jitter(2);
      glyph.s.forEach((stroke) => {
        const pts = densify(stroke.map(([gx, gy]) => {
          const px = ox + gx * w * scale + (1 - gy) * size * slant;
          const py = oy + gy * size * scale;
          return [px + jitter(0.7), py + jitter(0.7)];
        }));
        let t = 0;
        const points = pts.map(([px, py], i) => {
          if (i > 0) t += Math.hypot(px - pts[i - 1][0], py - pts[i - 1][1]) / (0.3 + rand() * 0.1);
          return { x: px, y: py, t };
        });
        addStroke(ink, { t: clock, p: 'pen', lw: 4.2 + rand() * 0.6, points });
        clock += t + 70 + rand() * 110;
      });
      x += w + size * 0.08;
      clock += 60 + rand() * 120;
    });
  });
  ink.h = Math.max(INK_START_HEIGHT, Math.ceil((y + LINE + TOP) / 100) * 100);
  return ink;
}
